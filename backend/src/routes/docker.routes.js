const express =
require("express");

const controller =
require(
    "../controllers/docker.controller"
);

const router =
express.Router();

/*
|--------------------------------------------------------------------------
| Docker Engine Information
|--------------------------------------------------------------------------
*/

router.get(
    "/info",
    controller.info
);

/*
|--------------------------------------------------------------------------
| Docker Images
|--------------------------------------------------------------------------
*/

router.get(
    "/images",
    controller.images
);

/*
|--------------------------------------------------------------------------
| Docker Networks
|--------------------------------------------------------------------------
*/

router.get(
    "/networks",
    controller.networks
);

/*
|--------------------------------------------------------------------------
| Docker Volumes
|--------------------------------------------------------------------------
*/

router.get(
    "/volumes",
    controller.volumes
);

/*
|--------------------------------------------------------------------------
| All Containers
|--------------------------------------------------------------------------
*/

router.get(
    "/containers",
    controller.containers
);

/*
|--------------------------------------------------------------------------
| Single Container
|--------------------------------------------------------------------------
*/

router.get(
    "/containers/:id",
    controller.container
);

module.exports = router;